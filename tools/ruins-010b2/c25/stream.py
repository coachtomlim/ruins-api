#!/usr/bin/env python3
"""Synthetic-only encrypted streaming rehearsal, no remote endpoints accepted.

Uses a public recipient created outside the capture VM. Never accepts a private key.
The standalone capture retains no private key. Restore uses a new isolated target.
"""
import subprocess as sp, pathlib, json, hashlib, sys, time, os, tarfile, io
os.umask(0o077)
IMAGE='postgres@sha256:00bc86618629af00d2937fdc5a5d63db3ff8450acf52f0636ec813c7f4902929'
ROOT=pathlib.Path('/dev/shm/ruins-c25-stream')
SRC='ruins-c25-stream-source'
DST='ruins-c25-stream-target'
APPS=['public','sl_sim','sl_sim_basic1_hosted_poc','sl_sim_basic1_postpilot']
SCHEMAS=APPS+['auth','storage','supabase_migrations']
def need(v,msg):
 if not v: raise RuntimeError(msg)
def run(a,data=None,ok=True):
 p=sp.run(a,input=data,stdout=sp.PIPE,stderr=sp.PIPE,timeout=60)
 if ok and p.returncode:raise RuntimeError('subprocess failed '+a[0]+' rc='+str(p.returncode))
 return p
def pg(n,a,data=None,ok=True):return run(['docker','exec','-i',n]+a,data,ok)
def sql(n,q,user='postgres',ok=True):return pg(n,['psql','-XqAt','-U',user,'-d','postgres','-v','ON_ERROR_STOP=1','-c',q],ok=ok)
def start(n):
 need(run(['docker','inspect',n],ok=False).returncode!=0,'name already in use')
 run(['docker','run','-d','--name',n,'--network','none','--memory','384m','--tmpfs','/var/lib/postgresql/data:rw,nosuid,size=268435456','-e','POSTGRES_USER=bootstrap','-e','POSTGRES_HOST_AUTH_METHOD=trust',IMAGE])
 for _ in range(150):
  if b'PostgreSQL init process complete' in run(['docker','logs',n]).stdout and pg(n,['pg_isready','-U','bootstrap'],ok=False).returncode==0:return
  time.sleep(.2)
 raise RuntimeError('startup timeout')
def fixture(n,rows):
 sql(n,'CREATE ROLE postgres LOGIN NOSUPERUSER CREATEDB CREATEROLE BYPASSRLS; CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE app_member NOLOGIN; GRANT app_member TO authenticated; CREATE ROLE supabase_auth_admin NOLOGIN; CREATE ROLE supabase_storage_admin NOLOGIN; ALTER DATABASE postgres OWNER TO postgres; ALTER SCHEMA public OWNER TO postgres;',user='bootstrap')
 sql(n,'CREATE SCHEMA auth AUTHORIZATION supabase_auth_admin; CREATE SCHEMA storage AUTHORIZATION supabase_storage_admin;',user='bootstrap')
 sql(n,'CREATE SCHEMA supabase_migrations;'+''.join('CREATE SCHEMA '+s+';' for s in APPS[1:]))
 for s in SCHEMAS:
  owner={'auth':'supabase_auth_admin','storage':'supabase_storage_admin'}.get(s,'postgres')
  sql(n,'SET ROLE '+owner+'; CREATE TABLE '+s+'.records(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,principal text NOT NULL,value text NOT NULL);',user='bootstrap')
  if rows:sql(n,'SET ROLE '+owner+'; INSERT INTO '+s+".records(principal,value) VALUES('alice','FAKE_ONLY_"+s+"'),('bob','FAKE_ONLY_B');",user='bootstrap')
 for s in ['auth','storage']:
  # Explicit fake baseline read permissions, not a recommended live grant.
  sql(n,'GRANT USAGE ON SCHEMA '+s+' TO postgres; GRANT SELECT ON '+s+'.records TO postgres; GRANT SELECT ON ALL SEQUENCES IN SCHEMA '+s+' TO postgres;',user='bootstrap')
 sql(n,"GRANT USAGE ON SCHEMA public TO authenticated; GRANT SELECT ON public.records TO authenticated; ALTER TABLE public.records ENABLE ROW LEVEL SECURITY; CREATE POLICY own_rows ON public.records TO authenticated USING(principal=current_setting('app.principal',true));")
def inv(n):
 result={}
 for s in SCHEMAS:
  b=sql(n,'select row_to_json(t)::text from '+s+'.records t order by 1').stdout
  result[s]={'rows':len(b.splitlines()),'sha256':hashlib.sha256(b).hexdigest(),'sequence':sql(n,'select last_value,is_called from '+s+'.records_id_seq').stdout.decode().strip()}
 result['roles']=sql(n,"select rolname,rolsuper,rolcreaterole,rolcreatedb,rolbypassrls,rolcanlogin from pg_roles where rolname !~ '^pg_' order by 1").stdout.decode()
 result['memberships']=sql(n,'select r.rolname,m.rolname,a.admin_option,a.inherit_option,a.set_option from pg_auth_members a join pg_roles r on r.oid=a.roleid join pg_roles m on m.oid=a.member order by 1,2').stdout.decode()
 result['policies']=sql(n,'select schemaname,tablename,policyname,roles,cmd,qual,with_check from pg_policies order by 1,2,3').stdout.decode()
 result['acl']=sql(n,"select n.nspname,c.relname,pg_get_userbyid(c.relowner),c.relacl,c.relrowsecurity from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in ("+','.join("'%s'"%s for s in SCHEMAS)+') order by 1,2').stdout.decode()
 return result
def stream(args,out,recipient,broken=False):
 # There is no plaintext dump file. bash pipefail propagates producer/compressor/age errors.
 import shlex
 cmd=' '.join(shlex.quote(x) for x in args)
 if broken:cmd="(printf FAKE_INCOMPLETE; exit 71)"
 with out.open('xb') as f:
  p=sp.run(['bash','-o','pipefail','-c',cmd+' | gzip -n -c | age -r '+shlex.quote(recipient)],stdout=f,stderr=sp.PIPE,timeout=60)
 if p.returncode:out.unlink(missing_ok=True);raise RuntimeError('pipeline rejected rc='+str(p.returncode))
 need(out.stat().st_size>100,'empty ciphertext')
def capture(recipient):
 need(recipient.startswith('age1') and len(recipient)==62,'public age recipient only')
 ROOT.mkdir(mode=0o700)
 start(SRC);fixture(SRC,True)
 need(sql(SRC,"select rolsuper from pg_roles where rolname=current_user").stdout.strip()==b'f','superuser rejected')
 # A realistic managed owner exposes the limitation of SHARE locks to the capture role.
 denied=sql(SRC,'BEGIN; LOCK TABLE auth.records IN SHARE MODE; ROLLBACK;',ok=False)
 need(denied.returncode!=0,'expected managed table lock denial')
 # Fake source is controlled by this harness; NO background writers exist in this run.
 before=inv(SRC)
 keeper=sp.Popen(['docker','exec','-i',SRC,'psql','-XqAt','-U','postgres','-d','postgres','-v','ON_ERROR_STOP=1'],stdin=sp.PIPE,stdout=sp.PIPE,stderr=sp.PIPE)
 keeper.stdin.write(b'BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY; SELECT pg_export_snapshot();\n');keeper.stdin.flush()
 snap=keeper.stdout.readline().decode().strip();need('-' in snap,'snapshot absent')
 manifest={'kind':'FAKE_ONLY_C25_STREAM','image':IMAGE,'snapshot':snap,'managed_lock_denied':True,'quiescence':'harness-owned synthetic no-writer source, not live proof','files':{},'inventory':before}
 try:
  # SQL role dump is diagnostic only: managed/platform role replay needs reconciliation.
  sets={'roles':['pg_dumpall','--roles-only','--no-role-passwords'],'schema':['pg_dump','-Fc','--schema-only','--snapshot='+snap]+sum((['-n',s] for s in APPS),[]),'data':['pg_dump','-Fc','--data-only','--snapshot='+snap]+sum((['-n',s] for s in SCHEMAS if s!='supabase_migrations'),[]),'history':['pg_dump','-Fc','--snapshot='+snap,'-n','supabase_migrations']}
  for label,args in sets.items():
   path=ROOT/(label+'.age');stream(['docker','exec',SRC]+args+['-U','postgres'],path,recipient)
   manifest['files'][path.name]={'bytes':path.stat().st_size,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
  need(inv(SRC)==before,'source drift')
  # Failure must remove partial ciphertext, and must not create a success receipt.
  bad=ROOT/'interrupted.age'
  try:stream(['false'],bad,recipient,True)
  except RuntimeError:pass
  else:raise RuntimeError('producer failure accepted')
  need(not bad.exists(),'partial ciphertext retained')
  # Encrypt/authenticate manifest itself, binding every member hash and inventory.
  run(['age','-r',recipient,'-o',str(ROOT/'manifest.age')],json.dumps(manifest,sort_keys=True).encode())
  # Outer tar contains ciphertext ONLY, never a plaintext manifest or database member.
  with tarfile.open(ROOT/'bundle.tar','w') as t:
   for p in sorted(ROOT.glob('*.age')):t.add(p,arcname=p.name)
  blob=(ROOT/'bundle.tar').read_bytes()
  receipt={'status':'C25_STREAM_CAPTURE_SYNTHETIC_ONLY','bytes':len(blob),'sha256':hashlib.sha256(blob).hexdigest(),'recipient':recipient,'members':sorted(p.name for p in ROOT.glob('*.age')),'producer_failure_rejected':True,'managed_share_lock_denied':True,'live':False,'lost_response':'No remote transfer or completion receipt exists yet'}
  print(json.dumps(receipt,sort_keys=True))
 finally:
  keeper.stdin.write(b'ROLLBACK;\n\\q\n');keeper.stdin.flush();keeper.communicate(timeout=10)
  run(['docker','rm','-fv',SRC],ok=False)
if __name__=='__main__':
 if len(sys.argv)==3 and sys.argv[1]=='capture':capture(sys.argv[2])
 else:raise SystemExit('capture PUBLIC_SYNTHETIC_RECIPIENT only; never supply live endpoint')
