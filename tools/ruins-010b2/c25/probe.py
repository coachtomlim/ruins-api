#!/usr/bin/env python3
"""Synthetic-only C2.5 restriction and consistency probe. No endpoint inputs."""
import subprocess as sp, json, time, hashlib, pathlib, sys
IMAGE='postgres@sha256:00bc86618629af00d2937fdc5a5d63db3ff8450acf52f0636ec813c7f4902929'
NAME='ruins-c25-probe'
APPS=['public','sl_sim','sl_sim_basic1_hosted_poc','sl_sim_basic1_postpilot']
ALL=APPS+['auth','storage','supabase_migrations']
checks=[]
def run(a,b=None,required=True):
 p=sp.run(a,input=b,stdout=sp.PIPE,stderr=sp.PIPE)
 if required and p.returncode: raise RuntimeError(a[0]+' failed: '+p.stderr.decode()[:300])
 return p
def pg(a,b=None,required=True):return run(['docker','exec','-i',NAME]+a,b,required)
def sql(q,user='postgres',required=True):return pg(['psql','-XqAt','-U',user,'-d','postgres','-v','ON_ERROR_STOP=1','-c',q],required=required)
def check(label,value):
 if not value:raise RuntimeError('CHECK_FAILED '+label)
 checks.append(label)
def command(q,user='postgres'):
 return ['docker','exec','-i',NAME,'psql','-XqAt','-U',user,'-d','postgres','-v','ON_ERROR_STOP=1','-c',q]
def hold(q):
 p=sp.Popen(['docker','exec','-i',NAME,'psql','-XqAt','-U','postgres','-d','postgres','-v','ON_ERROR_STOP=1'],stdin=sp.PIPE,stdout=sp.PIPE,stderr=sp.PIPE)
 p.stdin.write((q+'\n').encode());p.stdin.flush()
 return p
def end(p):
 p.stdin.write(b'ROLLBACK;\n\\q\n');p.stdin.flush();p.communicate(timeout=10)
def inventory():
 # Includes values and definitions, not just row counts. Quiescent fixture only.
 q="select n.nspname,c.relname,c.relkind,c.relacl::text,c.relrowsecurity from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in ("+','.join("'%s'"%s for s in ALL)+") order by 1,2"
 b=sql(q).stdout
 for s in ALL:b+=sql('select row_to_json(t)::text from '+s+'.records t order by 1').stdout
 b+=sql("select rolname,rolsuper,rolcreaterole,rolbypassrls from pg_roles where rolname !~ '^pg_' order by 1").stdout
 return hashlib.sha256(b).hexdigest()
def main():
 run(['docker','run','-d','--name',NAME,'--network','none','--tmpfs','/var/lib/postgresql/data:rw,nosuid,size=268435456','-e','POSTGRES_USER=bootstrap','-e','POSTGRES_HOST_AUTH_METHOD=trust',IMAGE])
 for _ in range(100):
  if b'PostgreSQL init process complete' in run(['docker','logs',NAME]).stdout and pg(['pg_isready','-U','bootstrap'],required=False).returncode==0:break
  time.sleep(.2)
 else:raise RuntimeError('startup timeout')
 sql('CREATE ROLE postgres LOGIN NOSUPERUSER CREATEDB CREATEROLE BYPASSRLS; CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE app_member NOLOGIN; GRANT app_member TO authenticated; ALTER DATABASE postgres OWNER TO postgres; ALTER SCHEMA public OWNER TO postgres;',user='bootstrap')
 sql('CREATE SCHEMA auth; CREATE SCHEMA storage; CREATE SCHEMA supabase_migrations;'+''.join('CREATE SCHEMA '+s+';' for s in APPS[1:]))
 for s in ALL:
  sql('CREATE TABLE '+s+'.records(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, principal text NOT NULL, value text NOT NULL); INSERT INTO '+s+".records(principal,value) VALUES('alice','FAKE_ONLY_"+s+"'),('bob','FAKE_ONLY_B');")
 sql("GRANT USAGE ON SCHEMA public TO authenticated; GRANT SELECT ON public.records TO authenticated; ALTER TABLE public.records ENABLE ROW LEVEL SECURITY; CREATE POLICY own_rows ON public.records TO authenticated USING(principal=current_setting('app.principal',true));")
 check('postgres_nonsuperuser',sql("select rolsuper from pg_roles where rolname=current_user").stdout.strip()==b'f')
 check('pg17_6',b'17.6' in pg(['pg_dump','--version']).stdout)
 check('rls_alice_only',sql("set role authenticated; set app.principal='alice'; select count(*) from public.records",user='bootstrap').stdout.strip()==b'1')
 check('anon_denied',sql('set role anon; select * from public.records',user='bootstrap',required=False).returncode!=0)
 # Global role dump without passwords is accessible without pg_authid SELECT.
 roles=pg(['pg_dumpall','-U','postgres','--roles-only','--no-role-passwords'])
 check('roles_export_nonsuperuser',b'CREATE ROLE authenticated' in roles.stdout)
 # Consistent snapshot for schema, data, and separately captured migration history.
 lock=hold('BEGIN ISOLATION LEVEL REPEATABLE READ; LOCK TABLE '+','.join(s+'.records' for s in ALL)+' IN SHARE MODE; SELECT pg_export_snapshot();')
 snap=lock.stdout.readline().decode().strip()
 check('snapshot_exported',bool(snap) and '-' in snap)
 before=inventory()
 writer=sql("SET lock_timeout='300ms'; UPDATE public.records SET value='CHANGED' WHERE id=1",required=False)
 check('concurrent_update_blocked',writer.returncode!=0 and b'lock timeout' in writer.stderr)
 ddl=sql("SET lock_timeout='300ms'; ALTER TABLE public.records ADD COLUMN forbidden int",required=False)
 check('concurrent_alter_blocked',ddl.returncode!=0 and b'lock timeout' in ddl.stderr)
 dumps={}
 for label,args in [('schema',['--schema-only']+sum((['-n',s] for s in APPS),[])),('data',['--data-only']+sum((['-n',s] for s in ALL if s!='supabase_migrations'),[])),('history',['-n','supabase_migrations'])]:
  p=pg(['pg_dump','-U','postgres','-Fc','--snapshot='+snap]+args)
  check(label+'_nonempty',len(p.stdout)>1000 and p.stdout.startswith(b'PGDMP'));dumps[label]=p.stdout
 check('stable_full_inventory',inventory()==before)
 # New relation DDL is not prevented by existing-table SHARE locks. Drift MUST reject.
 sql('CREATE TABLE public.concurrent_ddl(x int)')
 check('new_relation_drift_detected',inventory()!=before)
 sql('DROP TABLE public.concurrent_ddl')
 # Sequence operations are nontransactional and are not pinned by exported snapshots.
 seq_before=sql('select last_value from public.records_id_seq').stdout
 sql("select nextval('public.records_id_seq')")
 check('sequence_drift_detected',sql('select last_value from public.records_id_seq').stdout!=seq_before)
 end(lock)
 check('expired_snapshot_rejected',pg(['pg_dump','-U','postgres','-Fc','--snapshot='+snap],required=False).returncode!=0)
 # Reproduce post-r2: private owned table and no new permissions for postgres.
 sql('CREATE ROLE ruins_owner NOLOGIN; CREATE SCHEMA ruins_private AUTHORIZATION ruins_owner; SET ROLE ruins_owner; CREATE TABLE ruins_private.secret(v text); INSERT INTO ruins_private.secret VALUES(\'FAKE\');',user='bootstrap')
 failed=pg(['pg_dump','-U','postgres','-Fc'],required=False)
 check('after_r2_whole_dump_denied',failed.returncode!=0 and b'ruins_private' in failed.stderr)
 check('pre_r2_guard_rejects',sql("select to_regnamespace('ruins_private') is null").stdout.strip()==b'f')
 # Never publish a complete archive from these diagnostic/drift runs.
 check('no_complete_artifact',not pathlib.Path('/dev/shm/ruins-c25.COMPLETE').exists())
 print(json.dumps({'status':'C25_DIAGNOSTIC_PASS_NOT_ACCEPTANCE','checks':checks,'count':len(checks),'image':IMAGE,'live_connection':False,'limitations':['No encrypted transfer or independent key recovery in this diagnostic','No live command pack accepted','All fixture schemas owned by postgres; managed ownership compatibility still pending','No clean fresh restore yet']},sort_keys=True))
try:main()
finally:
 run(['docker','rm','-fv',NAME],required=False)
